_COMPILED_PATTERNS = {
    topic: tuple(re.compile(pattern) for pattern in patterns)
    for topic, patterns in TOPIC_PATTERNS.items()
}
_COMPILED_UNMAPPED_REASON_PATTERNS = tuple(
    (reason, tuple(re.compile(pattern) for pattern in patterns))
    for reason, patterns in UNMAPPED_REASON_PATTERNS
)


@dataclass(slots=True)
class TagMappingResult:
    tag: str
    normalized_tag: str
    topics: list[str]
    matched_rules: list[str]
    status: str
    review_reason: str | None = None

    def to_dict(self) -> dict[str, object]:
        return asdict(self)


def normalize_label(value: str | None) -> str:
    if not value:
        return ""
    return _NORMALIZE_RE.sub(" ", value.lower()).strip()


def map_tag_to_topics(tag: str) -> TagMappingResult:
    normalized = normalize_label(tag)
    matched_topics: set[str] = set()
    matched_rules: list[str] = []

    exact_topics = EXACT_TOPIC_MAP.get(normalized)
    if exact_topics is not None:
        matched_topics.update(
            canonical_topic
            for topic in exact_topics
            if (canonical_topic := canonicalize_topic(topic)) is not None
        )
        if exact_topics:
            matched_rules.append(f"exact:{normalized}")

    for topic, patterns in _COMPILED_PATTERNS.items():
        for pattern in patterns:
            if pattern.search(normalized):
                canonical_topic = canonicalize_topic(topic)
                if canonical_topic is not None:
                    matched_topics.add(canonical_topic)
                matched_rules.append(f"pattern:{topic}:{pattern.pattern}")
                break

    topics = sorted(matched_topics, key=CONTROLLED_TOPICS.index)
    if topics:
        status = "mapped" if len(topics) == 1 else "multi_topic"
        return TagMappingResult(
            tag=tag,
            normalized_tag=normalized,
            topics=topics,
            matched_rules=matched_rules,
            status=status,
        )

    return TagMappingResult(
        tag=tag,
        normalized_tag=normalized,
        topics=[],
        matched_rules=[],
        status="unmapped",
        review_reason=classify_unmapped_tag_reason(normalized),
    )


def classify_unmapped_tag_reason(normalized_tag: str) -> str:
    if not normalized_tag:
        return "empty_tag"

    for reason, patterns in _COMPILED_UNMAPPED_REASON_PATTERNS:
        if any(pattern.search(normalized_tag) for pattern in patterns):
            return reason

    return "needs_manual_review"


def map_tags(tags: list[str] | tuple[str, ...]) -> list[TagMappingResult]:
    return [map_tag_to_topics(tag) for tag in tags if isinstance(tag, str) and tag.strip()]


def infer_topics_from_tags(tags: list[str] | tuple[str, ...]) -> list[str]:
    seen: set[str] = set()
    for result in map_tags(tags):
        seen.update(result.topics)
    return sorted(seen, key=CONTROLLED_TOPICS.index)
